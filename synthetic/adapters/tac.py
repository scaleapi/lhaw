"""
TAC (TheAgentCompany) Adapter
=============================
Convert TAC tasks to UnifiedTask format.

S3 Trajectories: Set LHAW_GOLDEN_TRAJECTORY_S3 env var to your S3 prefix, e.g.
  s3://your-bucket/lhaw/tac/gt_trajectory/{task_name}.json
Checkpoints: task_pairs_agentcompany/{task_name}/checkpoints.md
"""

import json
import re
from pathlib import Path
from typing import List, Optional

from ..core import UnifiedTask
from .base import BaseTaskAdapter


class TACAdapter(BaseTaskAdapter):
    """Adapter for TheAgentCompany tasks."""

    DOMAIN = "tac"
    S3_TRAJECTORY_PREFIX = "research/lhaw/tac/gt_trajectory"

    def __init__(self, task_pairs_dir: str = "task_pairs_agentcompany"):
        self.task_pairs_dir = Path(task_pairs_dir)

    def load_task(
        self,
        task_id: str,
        trajectory_path: Optional[str] = None,
        **kwargs,
    ) -> UnifiedTask:
        """
        Load a TAC task into unified format.

        Args:
            task_id: Task name (e.g., "finance_check_attendance_payroll")
            trajectory_path: S3 or local path to golden trajectory

        Returns:
            UnifiedTask with prompt, checkpoints, etc.
        """
        task_dir = self.task_pairs_dir / task_id

        # Load task.json
        task_json_path = task_dir / "task.json"
        if not task_json_path.exists():
            raise FileNotFoundError(f"task.json not found: {task_json_path}")

        with open(task_json_path) as f:
            task_data = json.load(f)

        prompt = task_data.get("primary_task", "")

        # Load checkpoints.md
        checkpoints = self.get_checkpoints(task_id)

        # Extract category from task name (e.g., "finance" from "finance_check_attendance_payroll")
        category = task_id.split("_")[0] if "_" in task_id else "unknown"

        return UnifiedTask(
            id=task_id,
            domain=self.DOMAIN,
            category=category,
            prompt=prompt,
            trajectory_path=trajectory_path,
            checkpoints=checkpoints,
        )

    def get_checkpoints(self, task_id: str) -> List[str]:
        """Parse checkpoints.md into list of checkpoint descriptions."""
        task_dir = self.task_pairs_dir / task_id
        checkpoints_path = task_dir / "checkpoints.md"
        if not checkpoints_path.exists():
            return []

        content = checkpoints_path.read_text()

        # Parse checkpoint sections
        # Format: ## Checkpoint N (Xpt)\n Description
        checkpoints = []
        pattern = r"## Checkpoint \d+.*?\n(.*?)(?=## Checkpoint|\Z)"
        matches = re.findall(pattern, content, re.DOTALL)

        for match in matches:
            checkpoint_text = match.strip()
            if checkpoint_text:
                checkpoints.append(checkpoint_text)

        return checkpoints

    def list_tasks(self) -> List[str]:
        """List all available TAC tasks (excludes generated underspecified variants)."""
        if not self.task_pairs_dir.exists():
            return []

        tasks = []
        for item in self.task_pairs_dir.iterdir():
            if item.is_dir() and (item / "task.json").exists():
                # Skip underspecified variants directory (generated by run_tac_underspec.py)
                if item.name == "underspecified":
                    continue
                tasks.append(item.name)

        return sorted(tasks)
