"""
MCP Server that provides a request_clarification tool for OpenHands.

This server exposes a tool that allows the agent to request clarification from
the task assigner. The responses are generated by an LLM to simulate the human
who assigned the task and has access to the complete task requirements.
"""

import base64
import json
import logging
import os
import sys
from typing import Tuple

from fastmcp import FastMCP
from tenacity import before_sleep_log, retry, stop_after_attempt, wait_fixed

from llm import llm_completion

logger = logging.getLogger(__name__)

# Create the FastMCP server instance
mcp = FastMCP("user")

USER_SIMULATOR_MODEL = os.environ.get("USER_SIMULATOR_MODEL", "openai/gpt-4.1-2025-04-14")

# Default task context note - helps user simulator translate task paths to container paths
# The agent runs in a Docker container with specific path mappings:
#   - Input files: /workspace/inputs/THE OWNCLOUD FOLDER/...
#   - Output files: /workspace/output/... (where evaluators check)
DEFAULT_TASK_CONTEXT = """ENVIRONMENT CONTEXT:
- For INPUT files: The agent can find them in /workspace/inputs/THE OWNCLOUD FOLDER/
- For OUTPUT files: The agent should save to /workspace/output/<filename>
  (The task may say "/THE OWNCLOUD FOLDER/file.ext" but the agent must use /workspace/output/ - they don't have write access elsewhere)
""".strip()


def load_primary_task() -> Tuple[str, str, list[str]]:
    """Load the primary task definition from the PRIMARY_TASK_B64 env var.

    The task definition is passed as a base64-encoded JSON string via
    environment variable to keep it out of the agent's filesystem.

    Returns:
        Tuple of (primary_task, underspecified_prompt, removed_values)
    """
    try:
        encoded = os.environ.get("PRIMARY_TASK_B64", "")
        if not encoded:
            return "No primary task definition available.", "", []

        task_def = json.loads(base64.b64decode(encoded).decode("utf-8"))

        primary_task = task_def.get("primary_task", "")
        underspecified_prompt = task_def.get("underspecified_task", "")

        removed_values = []
        if "removed_segments" in task_def:
            for seg in task_def["removed_segments"]:
                if isinstance(seg, dict) and seg.get("value"):
                    removed_values.append(seg["value"])

        return primary_task, underspecified_prompt, removed_values
    except Exception as e:
        return f"Error reading primary task: {str(e)}", "", []


def generate_user_response(
    question: str,
    context: str,
    primary_task: str,
    underspecified_prompt: str,
    removed_values: list[str],
) -> str:
    """Generate a human-like response using an LLM.

    Args:
        question: The agent's question
        context: Context about what the agent was doing
        primary_task: The complete task requirements
        underspecified_prompt: The partial prompt the agent actually sees
        removed_values: List of values that were removed from the complete prompt

    Returns:
        A natural human-like response that answers the question
    """
    # Check if API credentials are available
    api_key = os.environ.get("LLM_API_KEY")
    if not api_key:
        raise ValueError("LLM_API_KEY not available. Cannot generate response.")

    # Format removed values for the prompt
    removed_values_str = ", ".join(removed_values) if removed_values else "None specified"
    underspec_str = underspecified_prompt or "Not provided"

    system_prompt = f"""You are simulating a user who has a task in mind but didn't fully specify it.

The user originally intended to give this COMPLETE prompt:
{primary_task}

But they actually gave this UNDERSPECIFIED version:
{underspec_str}

The parts that were removed/made vague:
{removed_values_str}

An AI assistant (who only sees the underspecified version) is now asking you a clarifying question.

Your job: Compare the two prompts, find what's MISSING from the underspecified version, and provide the EXACT information from the complete prompt.

Guidelines:
- Find the EXACT values that are in the complete prompt but missing from the underspecified one
- Provide those specific values (times, names, dates, numbers, phrases, etc.)
- Be concise - just answer what's asked
- Don't reveal you're a simulation

{DEFAULT_TASK_CONTEXT}
"""

    user_prompt = f"The assistant asks: {question}"
    if context:
        user_prompt += f"\n\nContext: {context}"

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]

    # Use inner function with tenacity for clean retry logic
    # MCP has 30s timeout, so 3 attempts × 8s + 2 waits = ~26s max (safe margin)
    @retry(
        stop=stop_after_attempt(3),
        wait=wait_fixed(0.5),  # Reduced wait for faster retries
        before_sleep=before_sleep_log(logger, logging.WARNING),
        reraise=True,
    )
    def _call_llm():
        return llm_completion(
            model=USER_SIMULATOR_MODEL,
            messages=messages,
            temperature=0.7,
            timeout=8,  # 8s per attempt to stay under 30s MCP timeout
        )

    try:
        response = _call_llm()
        return response
    except Exception as e:
        print(
            f"❌ User simulator failed after retries: {e}\n" f"Model: {USER_SIMULATOR_MODEL}",
            file=sys.stderr,
            flush=True,
        )
        return (
            "I'm not sure about that specific detail. Could you proceed with a reasonable default?"
        )


@mcp.tool()
async def ask_user(
    question: str,
    context: str = "",
) -> str:
    """Ask the user a clarifying question to get more information about the task. Use this when the task is ambiguous or you need specific details to proceed.

    Args:
        question: The clarifying question to ask the user.
        context: Optional additional context (e.g., conversation history summary)

    Returns:
        The user's response with the requested information.
    """
    # Load the primary task description
    primary_task, underspecified_prompt, removed_values = load_primary_task()

    # Generate a human-like response using an LLM
    response = generate_user_response(
        question=question,
        context=context,
        primary_task=primary_task,
        underspecified_prompt=underspecified_prompt,
        removed_values=removed_values,
    )

    return response


if __name__ == "__main__":
    mcp.run()
